import json
import os
import torch
from torch.utils.data import Dataset

from lens.utils.image_processing import resize_and_pad_image

class PrismBenchDataset(Dataset):
    """
    PrismBench Dataset Loader
    - Loads the JSON file generated by GPT + VLM (silver_dataset.json)
    - Supports raw `annotator_results` records and validates agreement before selecting the training target
    - Extracts binary preference label (A or B) for MarginRankingLoss (1.0 for A, -1.0 for B)
    - Extracts 3D Category Scores (0 or 1) for BCEWithLogitsLoss (Existence, Appearance, Interaction)
    """
    def __init__(self, json_path, processor=None):
        self.processor = processor
        try:
            with open(json_path, 'r') as f:
                self.data = json.load(f)
        except FileNotFoundError:
            print(f"Warning: Dataset not found at {json_path}. Creating a dummy dataset of length 10 for testing.")
            self.data = [self._generate_dummy_item() for _ in range(10)]

    def _generate_dummy_item(self):
        return {
            "task_id": "0001",
            "prompt": "A photo of [Subject A], [Subject B] walking in a cyberpunk city.",
            "subject_count": 2,
            "subject_refs": [
                {"id": "Subject A", "image_path": "./data/refs/cat_01.jpg"},
                {"id": "Subject B", "image_path": "./data/refs/dog_02.jpg"}
            ],
            "image_A_path": "./data/generated/gemini_0001.jpg",
            "image_B_path": "./data/generated/mosaic_0001.jpg",
            "annotator_results": [
                {
                    "annotator_id": "ann_01",
                    "preference": "A",
                    "category_scores_A": {
                        "existence": 1,
                        "appearance": 0,
                        "interaction": 0
                    },
                    "category_scores_B": {
                        "existence": 0,
                        "appearance": 0,
                        "interaction": 0
                    }
                },
                {
                    "annotator_id": "ann_02",
                    "preference": "A",
                    "category_scores_A": {
                        "existence": 1,
                        "appearance": 0,
                        "interaction": 1
                    },
                    "category_scores_B": {
                        "existence": 0,
                        "appearance": 0,
                        "interaction": 0
                    }
                }
            ],
            "metadata": {"source": "GPT Automated Subject Generation"}
        }

    def __len__(self):
        return len(self.data)

    def _select_annotation(self, item):
        annotator_results = item.get("annotator_results", [])
        if not annotator_results:
            return item

        # Check preference consistency
        first_pref = annotator_results[0].get("preference")
        for current in annotator_results[1:]:
            if current.get("preference") != first_pref:
                raise ValueError(f"Inconsistent preference labels found for task_id={item.get('task_id', 'unknown')}")

        # Average category scores across all annotators
        avg_scores_A = {"existence": 0.0, "appearance": 0.0, "interaction": 0.0}
        avg_scores_B = {"existence": 0.0, "appearance": 0.0, "interaction": 0.0}
        num_anns = len(annotator_results)

        for ann in annotator_results:
            cat_A = ann.get("category_scores_A", {})
            cat_B = ann.get("category_scores_B", {})
            
            for key in avg_scores_A:
                avg_scores_A[key] += float(cat_A.get(key, 0))
                avg_scores_B[key] += float(cat_B.get(key, 0))
                
        for key in avg_scores_A:
            avg_scores_A[key] /= num_anns
            avg_scores_B[key] /= num_anns

        return {
            "preference": first_pref,
            "category_scores_A": avg_scores_A,
            "category_scores_B": avg_scores_B
        }

    def __getitem__(self, idx):
        item = self.data[idx]
        annotation = self._select_annotation(item)
        
        # 1. Binary Preference Label (1.0 if A is preferred, -1.0 if B is preferred)
        pref_choice = annotation.get("preference", "A")
        pref_label = 1.0 if pref_choice == "A" else -1.0
        
        # 2. Category Scores (3-tier orthogonal: Existence, Appearance, Interaction)
        # category_scores_A/B are the final image-level diagnostic scores
        cat_A = annotation.get("category_scores_A", {})
        cat_B = annotation.get("category_scores_B", {})
        
        target_A = [
            float(cat_A.get("existence", 0)),
            float(cat_A.get("appearance", 0)),
            float(cat_A.get("interaction", 0))
        ]
        
        target_B = [
            float(cat_B.get("existence", 0)),
            float(cat_B.get("appearance", 0)),
            float(cat_B.get("interaction", 0))
        ]
        
        # 3. Text and Image inputs
        prompt = item.get("prompt", "")
        subject_refs = item.get("subject_refs", [])
        image_A_path = item.get("image_A_path", "")
        image_B_path = item.get("image_B_path", "")
        
        # 4. Standardized Image Processing (Resized & Padded to 512x512)
        base_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
        
        def load_and_norm(rel_path):
            abs_path = os.path.join(base_dir, rel_path)
            # This utility handles >512 downscaling, <512 skipping upscale, and white padding
            return resize_and_pad_image(abs_path, target_size=(512, 512))

        if self.processor is None:
            raise ValueError("Processor must be provided to PrismBenchDataset to load images. Please pass processor=AutoProcessor.from_pretrained(...)")
        
        # Make sure the processor has a pad_token assigned, otherwise padding="max_length" will crash
        if getattr(self.processor, "tokenizer", None) and self.processor.tokenizer.pad_token is None:
            self.processor.tokenizer.pad_token = self.processor.tokenizer.eos_token

        ref_images = [load_and_norm(ref["image_path"]) for ref in subject_refs]
        img_A = load_and_norm(image_A_path)
        img_B = load_and_norm(image_B_path)
        
        # Qwen3.5 expects multimodal placeholders to come from the chat template.
        # Raw "<image>" text can leave the model with zero image tokens even when pixel_values exist.
        def build_text_prompt():
            content = []
            for _ in ref_images:
                content.append({"type": "image"})
            content.append({"type": "image"})
            content.append({
                "type": "text",
                "text": (
                    "You are evaluating a multi-subject personalization result. "
                    "The first images are subject references. The last image is the generated candidate. "
                    f"Prompt: {prompt}"
                ),
            })
            messages = [{"role": "user", "content": content}]
            return self.processor.apply_chat_template(
                messages,
                tokenize=False,
                add_generation_prompt=False,
            )

        text_prompt = build_text_prompt()

        # Qwen3.5 multimodal prompts can contain a large number of image placeholder tokens.
        # Truncating here can delete part of those placeholders and break alignment with pixel_values.
        inputs_A = self.processor(
            text=[text_prompt],
            images=ref_images + [img_A],
            return_tensors="pt",
            padding=False,
            truncation=False,
        )
        inputs_B = self.processor(
            text=[text_prompt],
            images=ref_images + [img_B],
            return_tensors="pt",
            padding=False,
            truncation=False,
        )

        out = {
            "task_id": item.get("task_id", ""),
            "input_ids_A": inputs_A["input_ids"].squeeze(0),
            "attention_mask_A": inputs_A["attention_mask"].squeeze(0),
            "pixel_values_A": inputs_A["pixel_values"],
            "input_ids_B": inputs_B["input_ids"].squeeze(0),
            "attention_mask_B": inputs_B["attention_mask"].squeeze(0),
            "pixel_values_B": inputs_B["pixel_values"],
            "preference_label": torch.tensor(pref_label, dtype=torch.float32),
            "category_scores_A": torch.tensor(target_A, dtype=torch.float32),
            "category_scores_B": torch.tensor(target_B, dtype=torch.float32)
        }

        if "mm_token_type_ids" in inputs_A:
            out["mm_token_type_ids_A"] = inputs_A["mm_token_type_ids"].squeeze(0)
            out["mm_token_type_ids_B"] = inputs_B["mm_token_type_ids"].squeeze(0)
        
        # Include image_grid_thw if the processor generates it (e.g. for Qwen2-VL architecture)
        if "image_grid_thw" in inputs_A:
            out["image_grid_thw_A"] = inputs_A["image_grid_thw"]
            out["image_grid_thw_B"] = inputs_B["image_grid_thw"]
            
        return out

import json
import torch
from torch.utils.data import Dataset
from PIL import Image

class PrismBenchDataset(Dataset):
    """
    PrismBench Dataset Loader
    - Loads the JSON file generated by GPT + VLM (silver_dataset.json)
    - Extracts Continuous Preference Scores for MarginRankingLoss
    - Extracts 5D Category Scores (0.0, 0.5, 1.0) for BCEWithLogitsLoss
    """
    def __init__(self, json_path, processor=None):
        self.processor = processor
        try:
            with open(json_path, 'r') as f:
                self.data = json.load(f)
        except FileNotFoundError:
            print(f"Warning: Dataset not found at {json_path}. Creating a dummy dataset of length 10 for testing.")
            self.data = [self._generate_dummy_item() for _ in range(10)]

    def _generate_dummy_item(self):
        return {
            "preference_score_A": 0.9, "preference_score_B": 0.2,
            "category_scores_A": {"class_5_omission": 0.0, "class_4_distortion": 0.0, "class_3_swapping": 0.0, "class_2_bleeding": 0.5, "class_1_misalignment": 0.0},
            "category_scores_B": {"class_5_omission": 1.0, "class_4_distortion": 0.0, "class_3_swapping": 0.0, "class_2_bleeding": 0.0, "class_1_misalignment": 0.0}
        }

    def __len__(self):
        return len(self.data)

    def __getitem__(self, idx):
        item = self.data[idx]
        
        # 1. Continuous Preference Scores
        pref_A = item.get("preference_score_A", 0.5)
        pref_B = item.get("preference_score_B", 0.5)
        
        # 2. Category Scores (3-tier: 0.0, 0.5, 1.0)
        cat_A = item.get("category_scores_A", {})
        cat_B = item.get("category_scores_B", {})
        
        # [Omission, Distortion, Swapping, Bleeding, Misalignment]
        target_A = [
            cat_A.get("class_5_omission", 0.0),
            cat_A.get("class_4_distortion", 0.0),
            cat_A.get("class_3_swapping", 0.0),
            cat_A.get("class_2_bleeding", 0.0),
            cat_A.get("class_1_misalignment", 0.0)
        ]
        
        target_B = [
            cat_B.get("class_5_omission", 0.0),
            cat_B.get("class_4_distortion", 0.0),
            cat_B.get("class_3_swapping", 0.0),
            cat_B.get("class_2_bleeding", 0.0),
            cat_B.get("class_1_misalignment", 0.0)
        ]
        
        # Simulated Output from Qwen AutoProcessor (seq_len=32)
        # In reality, this will involve loading the image from item["stitched_image_path"]
        seq_len = 32
        
        return {
            "input_ids_A": torch.randint(0, 1000, (seq_len,)),
            "attention_mask_A": torch.ones(seq_len),
            "input_ids_B": torch.randint(0, 1000, (seq_len,)),
            "attention_mask_B": torch.ones(seq_len),
            "preference_score_A": torch.tensor([pref_A], dtype=torch.float32),
            "preference_score_B": torch.tensor([pref_B], dtype=torch.float32),
            "category_scores_A": torch.tensor(target_A, dtype=torch.float32),
            "category_scores_B": torch.tensor(target_B, dtype=torch.float32)
        }

import torch
from torch.utils.data import Dataset

class PrismBenchDataset(Dataset):
    """
    PrismBench Dataset Loader
    - Formats the stitched images (Refs + Gen A, Gen B)
    - Provides Preference Scores (continuous) for MarginRankingLoss
    - Provides Category Scores (4D vector with 0.0, 0.5, 1.0) for BCEWithLogitsLoss
    """
    def __init__(self, length=20):
        # Currently a dummy structure to allow for code validation.
        # Needs to be replaced with JSON loader + Image Processor.
        self.length = length

    def __len__(self):
        return self.length

    def __getitem__(self, idx):
        # Simulated Output from Qwen AutoProcessor
        seq_len = 32
        
        return {
            # Features for Image A (e.g. Generated by Gemini)
            "input_ids_A": torch.randint(0, 1000, (seq_len,)),
            "attention_mask_A": torch.ones(seq_len),
            
            # Features for Image B (e.g. Generated by MOSAIC)
            "input_ids_B": torch.randint(0, 1000, (seq_len,)),
            "attention_mask_B": torch.ones(seq_len),
            
            # MarginRankingLoss Targets (Continuous 0.0 to 1.0)
            "preference_score_A": torch.tensor([0.9]),
            "preference_score_B": torch.tensor([0.2]),
            
            # BCEWithLogitsLoss Target: 4-dim Multi-Label Vector
            # [Collapse, Swapping, Bleeding, Misalignment]
            # Values can be 0.0 (No), 0.5 (Maybe), 1.0 (Yes)
            "category_scores_A": torch.tensor([0.0, 0.0, 0.5, 0.0]),
            "category_scores_B": torch.tensor([1.0, 0.0, 0.0, 0.0])
        }

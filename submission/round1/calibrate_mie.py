"""Fit dimension-specific MIE routing baselines on a held-out calibration set.

Calibration images are generated by frozen OmniGen2 one-shot. MIE scores them,
then this script stores robust median/MAD statistics separately for each entity
count. The official Round-1 tasks are excluded from this set.
"""
from __future__ import annotations

import argparse
import json
import statistics
from pathlib import Path

from PIL import Image

import common


def robust_stats(values: list[float]) -> dict:
    median = statistics.median(values)
    mad = statistics.median(abs(value - median) for value in values)
    # Keep routing numerically stable when a sigmoid head is tightly clustered.
    scale = max(1.4826 * mad, 0.02)
    return {
        "n": len(values),
        "median": float(median),
        "mad": float(mad),
        "scale": float(scale),
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", required=True)
    ap.add_argument("--images", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--raw_out", required=True)
    args = ap.parse_args()

    tasks = common.load_tasks(args.data)
    critic = common.build_critic()
    image_dir = Path(args.images)
    grouped: dict[int, dict[str, list[float]]] = {}
    raw_path = Path(args.raw_out)
    raw_path.parent.mkdir(parents=True, exist_ok=True)

    with raw_path.open("w", encoding="utf-8") as fout:
        for index, task in enumerate(tasks):
            image_path = image_dir / f"{task.task_id}.png"
            if not image_path.exists():
                raise FileNotFoundError(f"calibration image missing: {image_path}")
            print(
                f"[CALIBRATION] {index+1:03d}/{len(tasks):03d} "
                f"task={task.task_id} entities={task.num_subjects} action=MIE_score",
                flush=True,
            )
            with Image.open(image_path) as loaded:
                scores = critic.score(loaded.convert("RGB"), task)
            group = grouped.setdefault(
                task.num_subjects, {dim: [] for dim in common.DIMS}
            )
            for dim in common.DIMS:
                group[dim].append(float(scores[dim]))
            fout.write(
                json.dumps(
                    {
                        "task_id": task.task_id,
                        "num_subjects": task.num_subjects,
                        **scores,
                    },
                    ensure_ascii=False,
                )
                + "\n"
            )
            print(
                f"[CALIBRATION] {index+1:03d}/{len(tasks):03d} "
                f"task={task.task_id} total={scores['total']:.4f} "
                f"E={scores['existence']:.3f} A={scores['appearance']:.3f} "
                f"I={scores['interaction']:.3f} status=OK",
                flush=True,
            )

    payload = {
        "version": 1,
        "method": "median_mad",
        "scale_floor": 0.02,
        "groups": {
            str(count): {
                dim: robust_stats(values) for dim, values in dimensions.items()
            }
            for count, dimensions in sorted(grouped.items())
        },
    }
    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(
        json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8"
    )
    print(f"[calibrate] wrote frozen baselines -> {out_path}")


if __name__ == "__main__":
    main()

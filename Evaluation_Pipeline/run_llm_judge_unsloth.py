import json
import argparse
import torch
import re
from PIL import Image
from unsloth import FastVisionModel

# 映射到真正的视觉语言模型 (VLMs)。注：Qwen3.5 是纯文本模型，无法处理图片！
# A100 支持 bfloat16，为了评测的精准度，建议跑 2B 和 7B 的 Qwen2-VL
MODEL_MAPPING = {
    "2": "unsloth/Qwen2-VL-2B-Instruct",
    "7": "unsloth/Qwen2-VL-7B-Instruct",
}

def load_manifest(manifest_path):
    with open(manifest_path, 'r') as f:
        return [json.loads(line) for line in f]

def save_manifest(manifest, manifest_path):
    with open(manifest_path, 'w') as f:
        for item in manifest:
            f.write(json.dumps(item) + '\n')

def extract_binary_score(text, key_pattern):
    match = re.search(rf"{key_pattern}.*?(0|1)", text, re.IGNORECASE)
    return int(match.group(1)) if match else 0

def evaluate_with_qwen(manifest, size_key):
    if size_key not in MODEL_MAPPING:
        print(f"Skipping size {size_key} as it's not a valid Vision Model in our mapping.")
        return manifest
        
    model_id = MODEL_MAPPING[size_key]
    print(f"🚀 Loading {model_id} via Unsloth...")
    
    # A100 拥有强大的算力和 80G 显存，我们使用 bfloat16 以获得最精确的打分，而不是 4-bit 牺牲精度
    model, processor = FastVisionModel.from_pretrained(
        model_id,
        load_in_4bit=False, 
        dtype=torch.bfloat16,
        use_gradient_checkpointing="unsloth",
    )
    FastVisionModel.for_inference(model) # 切换到极限推理加速模式
    
    preference_key = f"qwen_{size_key}b_preference"
    cat_bleeding_key = f"qwen_{size_key}b_attr_bleeding"
    cat_swapping_key = f"qwen_{size_key}b_sem_swapping"
    cat_collapse_key = f"qwen_{size_key}b_ent_collapse"
    
    for idx, item in enumerate(manifest):
        if preference_key in item and cat_bleeding_key in item: 
            continue
            
        print(f"Evaluating {idx+1}/{len(manifest)}: {item['task_id']}")
        
        model_A_img_path = item['pair']['model_A_image']
        model_B_img_path = item['pair']['model_B_image']
        
        image_paths = item['reference_images'] + [model_A_img_path, model_B_img_path]
        images = [Image.open(img_path).convert("RGB") for img_path in image_paths]
        
        instruction = (
            f"You are an expert image evaluator.\n"
            f"The first {len(item['reference_images'])} images are the Reference Subjects.\n"
            f"The last TWO images are generated by Model A and Model B, respectively.\n"
            f"Prompt used: '{item['prompt']}'\n"
            f"Evaluate both generated images based on the Reference Subjects.\n"
            f"Please output your evaluation exactly in the following format:\n"
            f"Preference: [Model A / Model B / Tie] - [Reason]\n"
            f"Model_A_Attribute_Bleeding: [0 or 1]\n"
            f"Model_A_Semantic_Swapping: [0 or 1]\n"
            f"Model_A_Entity_Collapse: [0 or 1]\n"
            f"Model_B_Attribute_Bleeding: [0 or 1]\n"
            f"Model_B_Semantic_Swapping: [0 or 1]\n"
            f"Model_B_Entity_Collapse: [0 or 1]"
        )
        
        content_list = [{"type": "image"}] * len(images)
        content_list.append({"type": "text", "text": instruction})
        
        messages = [
            {"role": "user", "content": content_list}
        ]
        
        text = processor.apply_chat_template(messages, add_generation_prompt=True)
        inputs = processor(
            text=[text], 
            images=images, 
            return_tensors="pt", 
            padding=True
        ).to("cuda")
        
        with torch.no_grad():
            outputs = model.generate(
                **inputs,
                max_new_tokens=256,
                temperature=0.1, 
            )
        
        # 只提取新生成的文本部分
        input_length = inputs.input_ids.shape[1]
        generated_ids = outputs[0][input_length:]
        generated_text = processor.decode(generated_ids, skip_special_tokens=True)
        
        # 提取各个类别分数
        item[preference_key] = generated_text.split('\n')[0] if '\n' in generated_text else generated_text
        
        # 存储 Model A 的三项指标
        item[cat_bleeding_key] = {
            "model_A": extract_binary_score(generated_text, "Model_A_Attribute_Bleeding"),
            "model_B": extract_binary_score(generated_text, "Model_B_Attribute_Bleeding")
        }
        item[cat_swapping_key] = {
            "model_A": extract_binary_score(generated_text, "Model_A_Semantic_Swapping"),
            "model_B": extract_binary_score(generated_text, "Model_B_Semantic_Swapping")
        }
        item[cat_collapse_key] = {
            "model_A": extract_binary_score(generated_text, "Model_A_Entity_Collapse"),
            "model_B": extract_binary_score(generated_text, "Model_B_Entity_Collapse")
        }
        
        if (idx + 1) % 10 == 0:
            save_manifest(manifest, args.manifest)

    return manifest

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument("--manifest", type=str, default="/workspace/master_eval_manifest.jsonl")
    parser.add_argument("--size", type=str, choices=["2", "7"], required=True, help="Qwen-VL model size to load")
    args = parser.parse_args()

    manifest = load_manifest(args.manifest)
    manifest = evaluate_with_qwen(manifest, args.size)
    save_manifest(manifest, args.manifest)
    print(f"✅ Finished evaluating with Qwen2-VL {args.size}B and updated manifest.")

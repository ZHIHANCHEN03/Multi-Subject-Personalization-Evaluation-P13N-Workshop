import json
import argparse
import torch
from PIL import Image
from unsloth import FastVisionModel

# 映射不同的参数规模到 Unsloth 支持的 Qwen3.5 模型 ID
MODEL_MAPPING = {
    "0.8": "unsloth/Qwen3.5-0.8B-Instruct",
    "2": "unsloth/Qwen3.5-2B-Instruct",
    "4": "unsloth/Qwen3.5-4B-Instruct",
}

def load_manifest(manifest_path):
    with open(manifest_path, 'r') as f:
        return [json.loads(line) for line in f]

def save_manifest(manifest, manifest_path):
    with open(manifest_path, 'w') as f:
        for item in manifest:
            f.write(json.dumps(item) + '\n')

def evaluate_with_qwen(manifest, size_key):
    model_id = MODEL_MAPPING.get(size_key, size_key)
    print(f"🚀 Loading {model_id} via Unsloth (4-bit)...")
    
    # 1. 按照 Unsloth 文档加载 Qwen 视觉模型
    model, processor = FastVisionModel.from_pretrained(
        model_id,
        load_in_4bit=True, # 开启 4bit 量化，极其省显存
        use_gradient_checkpointing="unsloth",
    )
    FastVisionModel.for_inference(model) # 切换到极限推理加速模式
    
    preference_key = f"qwen_{size_key}b_preference"
    cat_bleeding_key = f"qwen_{size_key}b_attr_bleeding"
    cat_swapping_key = f"qwen_{size_key}b_sem_swapping"
    cat_collapse_key = f"qwen_{size_key}b_ent_collapse"
    
    for idx, item in enumerate(manifest):
        if preference_key in item and cat_bleeding_key in item: 
            continue
            
        print(f"Evaluating {idx+1}/{len(manifest)}: {item['task_id']}")
        
        # 2. 准备图片
        # 对于 Pair 结构，我们需要比较两张图
        model_A_img_path = item['pair']['model_A_image']
        model_B_img_path = item['pair']['model_B_image']
        
        image_paths = item['reference_images'] + [model_A_img_path, model_B_img_path]
        images = [Image.open(img_path).convert("RGB") for img_path in image_paths]
        
        # 3. 组装 Qwen-VL 标准的 Chat Template (针对 Pair 比较)
        instruction = (
            f"You are an expert image evaluator.\n"
            f"The first {len(item['reference_images'])} images are the Reference Subjects.\n"
            f"The last TWO images are generated by Model A and Model B, respectively.\n"
            f"Prompt used: '{item['prompt']}'\n"
            f"Evaluate both generated images based on the Reference Subjects.\n"
            f"Please output your evaluation based on our taxonomy:\n"
            f"1. Preference: (Which model do you prefer and why? Model A, Model B, or Tie?)\n"
            f"2. Model_A_Attribute_Bleeding: (0 or 1)\n"
            f"3. Model_A_Semantic_Swapping: (0 or 1)\n"
            f"4. Model_A_Entity_Collapse: (0 or 1)\n"
            f"5. Model_B_Attribute_Bleeding: (0 or 1)\n"
            f"6. Model_B_Semantic_Swapping: (0 or 1)\n"
            f"7. Model_B_Entity_Collapse: (0 or 1)"
        )
        
        # 构建 messages
        content_list = [{"type": "image"}] * len(images)
        content_list.append({"type": "text", "text": instruction})
        
        messages = [
            {"role": "user", "content": content_list}
        ]
        
        # 4. 使用 Processor 进行预处理
        text = processor.apply_chat_template(messages, add_generation_prompt=True)
        inputs = processor(
            text=[text], 
            images=images, 
            return_tensors="pt", 
            padding=True
        ).to("cuda")
        
        # 5. 推理生成
        with torch.no_grad():
            outputs = model.generate(
                **inputs,
                max_new_tokens=128,
                temperature=0.1, # 降低温度，确保打分稳定
            )
        
        # 6. 解析输出
        generated_text = processor.batch_decode(outputs, skip_special_tokens=True)[0]
        # print(f"Output: {generated_text}")
        
        # 这里你可以写一个简单的正则，把模型输出里的 preference 结果和三个 category 的 0/1 提取出来
        # 目前暂时把原始文本存在 preference 里，你需要根据实际输出调整提取逻辑
        item[preference_key] = generated_text 
        item[cat_bleeding_key] = "TODO_Extract_0_or_1" 
        item[cat_swapping_key] = "TODO_Extract_0_or_1" 
        item[cat_collapse_key] = "TODO_Extract_0_or_1" 
        
        # 每跑 10 个保存一次，防止意外中断
        if (idx + 1) % 10 == 0:
            save_manifest(manifest, args.manifest)

    return manifest

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument("--manifest", type=str, default="/workspace/master_eval_manifest.jsonl")
    parser.add_argument("--size", type=str, choices=["0.8", "2", "4"], required=True, help="Qwen model size to load")
    args = parser.parse_args()

    manifest = load_manifest(args.manifest)
    manifest = evaluate_with_qwen(manifest, args.size)
    save_manifest(manifest, args.manifest)
    print(f"✅ Finished evaluating with Qwen3.5 {args.size}B and updated manifest.")
